/**
 * @file av_sync_config.h
 * @brief 集中设置视频等待、迟到丢帧和 Seek 等待的时间限制
 * @details
 * Player 在创建时间轴和同步节点时传入这些设置，它们分别守在不同时间尺度上：
 * 1. 稳态播放：视频帧落后主时钟多少才跳过（每帧决策，百毫秒量级）；
 * 2. 时钟源失效：音频位置多久不前进就改用系统单调时钟（需扣掉设备缓冲，数百毫秒）；
 * 3. 定位卡死：Seek 后所有轨道多久仍未就绪就整图报错（兜底，数秒）。
 *
 * 三个值之间存在先后关系，修改时不要只看单个数字：
 * - late_drop_us_ 必须明显大于调度抖动（节点默认轮询周期 5 ms 的 10 倍以上），否则会持续丢帧；
 * - reanchor_timeout_ 必须大于音频设备缓冲时长（默认 200 ms，最大可配 2000 ms），
 *   否则"设备里还排着声音、线程暂时没写新数据"这种正常停顿会被误判为卡死；
 * - seek_timeout_ 必须大于 reanchor_timeout_，否则慢设备上的正常 Seek 会被判成失败
 */

#pragma once

#include <chrono>
#include <cstdint>

namespace mediacore {

/**
 * @struct SyncConfig
 * @brief 音画同步的时间参数
 * @details 配置在播放前确定，由 Player 校验其有效性；播放期间不要并发修改同一实例。
 *          注意三个字段的单位并不相同：late_drop_us_ 为微秒（与帧 PTS 的计算域一致），
 *          另外两个为毫秒。新增参数时优先使用 std::chrono 类型，避免按错数量级。
 */
struct SyncConfig final {
    /**
     * @brief 视频帧落后于当前主时钟超过此时长时跳过该帧，默认 100 ms
     * @details
     * 主时钟是视频参考的播放位置，正常来自音频，音频失效时来自系统单调时钟
     * 判定只看迟到方向：早到的帧会等待，不会因为"太早"被丢。
     *
     * 取 100 ms 的理由：
     * - 下界：必须明显大于"一帧时长 + 调度抖动"。节点每 5 ms 轮询一次，线程唤醒抖动
     *   通常 1–5 ms；100 ms 在 25/30 fps 下约 2.5–3 帧，不会因一次调度延迟就丢帧。
     * - 上界：音频领先画面约 45 ms 开始可察觉，90 ms 左右到达可接受边界
     *   （ITU-R BT.1359 量级）。丢帧会让画面落后于音频，属于更敏感的方向，
     *   所以 100 ms 已接近上沿。
     * - 语义：音频是主时钟、不能变速，画面落后时只有"丢帧追上"和"持续偏移"两条路；
     *   该值等价于"允许偶尔卡 3 帧，但不允许口型持续不同步"。
     *
     * 调参参考：60 fps 内容可取 50–70 ms；24 fps 电影用 100 ms 已偏松
     */
    std::int64_t late_drop_us_{100'000};

    /**
     * @brief 音频播放位置停止前进后，改用系统计时之前的等待时长，默认 500 ms
     * @details
     * 音频输出节点周期上报播放位置；超过阈值仍未前进，说明主时钟源失效
     * （设备断流、欠载、轨道提前结束），此时改用 steady_clock 继续推进画面
     * 音频位置恢复后会重新以音频为准，因此可能产生一次位置回退
     *
     * 取 500 ms 的理由：
     * - 必须大于设备缓冲：默认 device_buffer_ms = 200 ms，最大可配 2000 ms
     *   设备里还排着声音时，线程不必立即写入，"位置不动"是正常现象。
     * - 必须大于一次欠载恢复耗时：ALSA 的 drop + prepare + 重新填充到起播阈值通常在几十毫秒量级。
     * - 必须小于用户能忍受的完全静止：画面 500 ms 不动用户就会认为卡住；
     *   设成 2 s 等于明知卡死还硬等。
     */
    std::chrono::milliseconds reanchor_timeout_{500};

    /**
     * @brief Seek 跳转后等待所有实际存在的轨道完成定位的时长，默认 5 秒
     * @details
     * 这里等的是"定位完成"，不是"播放完成"，也不是只等音频轨：
     * - 纯视频文件等视频轨，纯音频文件等音频轨，双路文件两条都等；
     * - 每条轨道通过 MarkReady 上报"已定位到目标位置，首份数据可以交付"；
     * - 最后一条轨道上报后由时间轴聚合，Player 才收到 SeekCompleted。
     *
     * 一次 Seek 包含：Demuxer 定位到目标之前最近的**关键帧**、解码器清内部缓存、
     * 视频从关键帧逐帧解码快进到目标、音频丢弃目标之前的采样。
     * 因此耗时主要由 GOP 长度决定，而不是文件大小：
     * - 全 I 帧素材（监控、剪辑代理）：< 20 ms；
     * - 常规 H.264（GOP 2–4 s）：100–400 ms；
     * - 长 GOP 4K 软解（GOP 10 s）：可能 1–3 s
     *
     * 取 5 秒的理由：约为最坏合法情况的两倍余量，正常本地文件只需 100–300 ms
     * 超时的动作是**停止整图并进入 Error**，而不是跳过未就绪的轨道强行播放，
     * 所以假阳性（误杀正在进行的合法 Seek）的代价远大于真阳性（用户重试一次）
     * 该值同时兜住内容本身的缺陷：双输出 Demuxer 使用有界队列，
     * 极端非交错容器可能让一条分支堵住另一条的定位，超时是那种情况的唯一出口
     */
    std::chrono::milliseconds seek_timeout_{5000};
};

}  // namespace mediacore
